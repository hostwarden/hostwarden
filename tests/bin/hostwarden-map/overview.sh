# tests/bin/hostwarden-map/overview.sh — memory/README.md, the
# workspace's overview page. Sourced by tests/bin/hostwarden-map.sh,
# in the order its PARTS lists, into the one shell every part
# shares; never run on its own.
# shellcheck shell=sh disable=SC2034 # read by the parts after it

OV="$M/README.md"
TODAY_D=$(days_ago 0)

# --- what the page reads beyond the maps' own fixture ----------------
# fw1: read nightly by an operations host, last reached 5 days ago.
# nas1: read nightly, reached today by the fleet run alone, whose
# finding text carries a count of its own that must not be added.
# web1: a hand run's headline wrapped over two lines, and an audit.
# pve1: an old run's findings cleared by a newer clean one.
# badcal: a Last connected: that is no date at all.
# udm1: read nightly, its last read 10 days ago found a CRITICAL, and
# tonight's run could not reach it -- neither contact nor a run.
# unas1: fleet read set up but waiting for the key line, so no
# nightly read covers it yet: 90 days, not 2.
printf -- '- Last connected: %s\n- Fleet read: ops1 (bundle linux, key line present, %s)\n' \
  "$(days_ago 5)" "$FRESH" >>"$M/machines/fw1.example.com/memory.md"
printf -- '- Fleet read: ops1 (bundle linux, key line present, %s)\n' \
  "$FRESH" >>"$M/machines/nas1.example.com/memory.md"
printf -- '- Last connected: %s\n' "$FRESH" >>"$M/machines/pve1.example.com/memory.md"
printf -- '- Last connected: 2026-02-30\n' >>"$M/machines/badcal.example.com/memory.md"
printf -- '- Fleet read: ops1 (bundle linux, key line present, %s)\n' \
  "$FRESH" >>"$M/machines/udm1.example.com/memory.md"
printf -- '- Last connected: %s\n- Fleet read: ops1 (bundle linux, waiting for the key line, %s)\n' \
  "$(days_ago 5)" "$FRESH" >>"$M/machines/unas1.example.com/memory.md"
cat >"$M/machines/udm1.example.com/changelog.log" <<EOF
[$(days_ago 10) 05:30] [ops1 as root] read-only: housekeeping: 1 CRITICAL — disk 99% full
  Detail: fleet read from ops1, bundle linux.
[$TODAY_D 05:30] [ops1 as root] read-only: housekeeping: 1 WARN — not read (exit 255): timeout
  Detail: fleet read from ops1, bundle linux; the host was not read.
EOF
cat >"$M/machines/nas1.example.com/changelog.log" <<EOF
[$TODAY_D 05:31] [ops1 as root] read-only: housekeeping: 2 WARN — pool tank 91% full; 3 WARN in the text
  Detail: fleet read from ops1, bundle linux.
EOF
cat >"$M/machines/web1.example.com/changelog.log" <<EOF
[$STALE 09:00] [alice as root]
Housekeeping: 1 CRITICAL, 2 WARN, all services OK
[$STALE 09:30] [alice as root] Security audit: 1 WARN, 1 INFO
EOF
cat >"$M/machines/pve1.example.com/changelog.log" <<EOF
[$STALE 09:00] [alice as root] Housekeeping: 3 WARN
[$FRESH 09:00] [alice as root] Housekeeping: all services OK
EOF

( cd "$R" && sh bin/hostwarden-map ) || bad "hostwarden-map exited non-zero with changelogs"
cp "$OV" "$TMP/overview-first.md"
( cd "$R" && sh bin/hostwarden-map ) || bad "second overview run exited non-zero"
cmp -s "$TMP/overview-first.md" "$OV" && ok \
  || bad "a same-day rerun over unchanged memory changed memory/README.md"

# --- the marker and the sections, in the issue's order ---------------
[ "$(head -n 1 "$OV")" = '<!-- Generated by bin/hostwarden-map from memory/. Do not edit by hand. -->' ] \
  && ok || bad "memory/README.md lacks hostwarden-wrap's own skip marker"
grep '^## ' "$OV" >"$TMP/ov-headings"
printf '%s\n' '## Sites' '## Services' '## Critical hosts' '## Open findings' \
  '## Expiring within 90 days' '## Backups without a tested restore' \
  '## Not connected lately' | cmp -s - "$TMP/ov-headings" && ok \
  || bad "the overview's sections are not the seven, in order"

# --- sites, each with its map ----------------------------------------
has "$OV" "- [home](maps/sites/home.md) — 8 hosts" "home links its map, personal hosts not counted"
has "$OV" "- [colo-fra](maps/sites/colo-fra.md) — 3 hosts" "colo-fra links its map"
has "$OV" "- [colo-ams](maps/sites/colo-ams.md) — 0 hosts" "a site with no host still listed"
has "$OV" "- No site on record: 3 hosts — [WAN](maps/wan.md)" \
  "no Site:, and a site topology.md never declared, counted as a gap"
haspart "$OV" "[maps/README.md](maps/README.md)" "the map index linked"

# --- what no rule records yet names the issue that fills it ----------
for i in 283 284 285 286; do
  haspart "$OV" "([hostwarden#$i](https://github.com/hostwarden/hostwarden/issues/$i))" \
    "a not-recorded section names #$i as a full link"
done
[ "$(grep -c '^Not recorded yet: ' "$OV")" -eq 4 ] && ok \
  || bad "not exactly four sections say their facts are not recorded yet"

# --- open findings: counts of the last runs, worst first -------------
has "$OV" "- [web1.example.com](machines/web1.example.com/changelog.log) — housekeeping $STALE: 1 CRITICAL, 2 WARN · security audit $STALE: 1 WARN, 1 INFO" \
  "a wrapped hand headline and an audit counted"
has "$OV" "- [nas1.example.com](machines/nas1.example.com/changelog.log) — housekeeping $TODAY_D: 2 WARN" \
  "a fleet run counted before its ' — ', its text left out"
lacks "$OV" "[pve1.example.com](machines/pve1.example.com/changelog.log)" \
  "a clean newer run clears an older run's findings"
[ "$(grep -n 'web1.example.com/changelog' "$OV" | cut -d: -f1)" -lt \
  "$(grep -n 'nas1.example.com/changelog' "$OV" | cut -d: -f1)" ] && ok \
  || bad "a host with a CRITICAL is not listed first"
has "$OV" "- Network: 1 WARN in [topology.md](topology.md) — [WAN](maps/wan.md)" \
  "the topology finding counted and linked"

# --- hosts not reached within their cadence ---------------------------
has "$OV" "- [fw1.example.com](machines/fw1.example.com/memory.md) — last contact $(days_ago 5); nightly, fleet read" \
  "a fleet-read host late after 2 days"
has "$OV" "- [web1.example.com](machines/web1.example.com/memory.md) — last contact $STALE; every 90 days" \
  "the newest changelog entry counts as contact"
has "$OV" "- [udm1.example.com](machines/udm1.example.com/memory.md) — last contact $(days_ago 10); nightly, fleet read" \
  "a fleet run that did not reach the host is not contact"
has "$OV" "- [udm1.example.com](machines/udm1.example.com/changelog.log) — housekeeping $(days_ago 10): 1 CRITICAL" \
  "a fleet run that did not reach the host is not its last run"
lacks "$OV" "(machines/unas1.example.com/memory.md)" \
  "a host waiting for its key line is not due nightly"
lacks "$OV" "days ago" "no line that changes by itself every day"
has "$OV" "- [pve3.example.com](machines/pve3.example.com/memory.md) — no contact on record; every 90 days" \
  "a host never reached is listed"
has "$OV" "- [badcal.example.com](machines/badcal.example.com/memory.md) — no contact on record; every 90 days" \
  "an impossible Last connected: is a gap, not a date"
lacks "$OV" "(machines/nas1.example.com/memory.md)" "a fleet run today is contact"
lacks "$OV" "(machines/pve1.example.com/memory.md)" "a host reached within 90 days is not late"

# --- a summary, never a second copy, never a personal host -----------
lacks "$OV" "pool tank" "a finding's own text is not copied"
lacks "$OV" "192.0.2." "no host's address is copied"
for p in localhost laptop.example.com buildbox.example.com root-do-not-quote-me; do
  lacks "$OV" "$p" "a personal host or file stays off the overview"
done

# --- a README.md a person wrote is theirs -----------------------------
printf '# Our notes\n' >"$OV"
( cd "$R" && sh bin/hostwarden-map ) 2>"$TMP/ov-err" || bad "a hand-written README.md failed the run"
[ "$(cat "$OV")" = "# Our notes" ] && ok || bad "a hand-written README.md was overwritten"
haspart "$TMP/ov-err" "was written by hand" "a skipped overview is said so"

# The page is the script's again for the parts after this one.
rm -f "$OV"
