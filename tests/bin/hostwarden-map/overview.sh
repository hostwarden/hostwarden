# A checkout cloned from a team's own copy names that copy as a clone
# address — its transport, port and path kept, since an ssh-only
# mirror has no https side and a forge's path need not end in .git —
# and says it is not upstream. What is one person's is taken out: a
# token in an https URL's user info, a query, a fragment, an ssh user
# other than git.
# A stand-in for ssh -G, first on PATH for these runs: the hostname,
# port and user an alias resolves to, as the user's ssh
# configuration would give them, and for any other host its own
# name, port 22 and this login, as ssh -G prints without one.
mkdir -p "$TMP/bin"
cat >"$TMP/bin/ssh" <<'EOF'
#!/bin/sh
for a; do :; done
case $a in
  forge) printf 'hostname forge.example.com\nport 2222\nuser git\n' ;;
  forge2.example.com) printf 'hostname forge2.example.com\nport 2222\nuser git\n' ;;
  v6) printf 'hostname 2001:db8::10\nport 2222\nuser git\n' ;;
  gh) printf 'hostname github.com\nport 22\nuser git\n' ;;
  *) printf 'hostname %s\nport 22\nuser %s\n' "$a" "$(id -un)" ;;
esac
EOF
chmod +x "$TMP/bin/ssh"
# origin_case <url> <clone line> <what> — set the origin, redraw,
# and expect the clone line.
origin_case() {
  if git -C "$R" remote get-url origin >/dev/null 2>&1; then
    git -C "$R" remote set-url origin "$1"
  else
    git -C "$R" remote add origin "$1"
  fi
  ( cd "$R" && PATH="$TMP/bin:$PATH" sh bin/hostwarden-map ) \
    || bad "hostwarden-map exited non-zero with origin $1"
  has "$OV" "    git clone $2 hostwarden" "$3"
}
