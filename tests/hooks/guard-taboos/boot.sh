# --- account files: blocked --------------------------------------
check deny 'vipw'
check deny 'vigr -s'
check deny 'ssh root@h "vipw"'
check deny 'echo "x:x:0:0::/:/bin/sh" >> /etc/passwd'
check deny 'echo x > /etc/shadow'
check deny ': > /etc/group'
check deny 'sed -i s/bash/sh/ /etc/passwd'
check deny 'sed -i -e "s/x/y/" /etc/gshadow'
check deny 'sed -i.bak s/a/b/ /etc/passwd'
check deny 'sed -ie s/a/b/ /etc/shadow'
check deny 'perl -pi -e s/x/y/ /etc/master.passwd'
check deny 'vi /etc/passwd'
check deny 'nano /etc/group'
check deny 'tee /etc/shadow < new'
check deny 'tee -a /etc/passwd < new'
check deny 'cp new /etc/passwd'
check deny 'cp -f /root/shadow.new /etc/shadow'
check deny 'mv /root/passwd.new /etc/passwd'
check deny 'rm /etc/group'
check deny 'install -m 640 new /etc/shadow'
check deny 'dd if=new of=/etc/passwd'
check deny 'cp new /etc/pwd.db'
check deny 'cp new /etc/spwd.db'
# runtime form
check deny "python3 -c \"open('/etc/passwd','a').write('x')\""
check deny "perl -e 'open(F,\">>/etc/shadow\")'"
# inside ssh host "…"
check deny 'ssh root@h "echo x >> /etc/passwd"'
check deny 'ssh root@h "sed -i s/a/b/ /etc/shadow"'
check deny 'ssh root@h "cp new /etc/group"'
check deny 'ssh root@h bash -s <<EOF
rm /etc/gshadow
EOF'

