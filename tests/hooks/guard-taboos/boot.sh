# runtime form
check deny "python3 -c \"open('/sys/firmware/efi/efivars/Boot0001-x','wb').write(b'x')\""
# inside ssh host "…"
check deny 'ssh root@h "efibootmgr -o 0001"'
check deny 'ssh root@h "update-grub"'
check deny 'ssh root@h "grub-install /dev/sda"'
