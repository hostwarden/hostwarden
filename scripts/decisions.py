def render_index(records):
    def cell(text):
        """A pipe in a title opens a column; the index would render wrong
        while --check still called it current."""
        return text.replace("|", "\\|")

    def link(record):
        return f"[{cell(record.title)}]({record.relative})"

    lines = [
        GENERATED,
        "",
        "# Decisions",
        "",
        (
            "One line per record. Read this before deciding something new, so "
            "a fresh decision does not quietly contradict a standing one. "
            "Records are never rewritten: a decision that stops holding is "
            "superseded and moves to *History*."
        ),
        "",
    ]

    def section(title, columns, rows):
        if rows:
            lines.extend(
                [
                    "## " + title,
                    "",
                    "| " + " | ".join(columns) + " |",
                    "| " + " | ".join([":---"] * len(columns)) + " |",
                ]
                + rows
                + [""]
            )

    def pick(*statuses):
        return sorted(
            (r for r in records if r.status in statuses),
            key=lambda r: r.id or r.path.stem,
            reverse=True,
        )

    by_id = {record.id: record for record in records if record.id}

    section(
        "In force",
        ["Decision", "Tags", "Rule"],
        [
            "| {} | {} | {} |".format(
                link(r),
                cell(", ".join(r.tags)) or "—",
                cell(", ".join(f"`{name}`" for name in r.rules)) or "—",
            )
            for r in pick("accepted")
        ],
    )
    section(
        "Proposed",
        ["Decision", "Waiting on", "Tags"],
        [
            "| {} | {} | {} |".format(
                link(r), cell(r.waiting_on) or "—", cell(", ".join(r.tags)) or "—"
            )
            for r in pick("proposed")
        ],
    )
    section(
        "History",
        ["Decision", "Status", "Replaced by"],
        [
            "| {} | {} | {} |".format(
                link(r),
                r.status,
                link(by_id[r.superseded_by]) if r.superseded_by in by_id else "—",
            )
            for r in pick("superseded", "rejected")
        ],
    )

    if not records:
        lines.extend(["No records yet.", ""])
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the index")
    mode.add_argument(
        "--check",
        action="store_true",
        help="report every problem and exit 1 if there is one",
    )
    parser.add_argument(
        "--root",
        # Hostwarden keeps its records in docs/adr/, the second of its
        # changes to this file (docs/adr/20260924-cite-only-rules.md).
        default="docs/adr",
        help="the decisions directory (default: docs/adr)",
    )
    parser.add_argument(
        "--repo",
        default=".",
        help="the repository root (default: the working directory)",
    )
    arguments = parser.parse_args()

    repo = Path(arguments.repo).resolve()
    decisions = (repo / arguments.root).resolve()
    if not decisions.is_dir():
        print(f"{arguments.root}/ does not exist", file=sys.stderr)
        return 1
    if repo not in decisions.parents:
        # Several checks state a record's location relative to the repository,
        # and a rule cites one by a repository-relative path, so a corpus
        # outside the tree can be neither reported nor cited. Said here rather
        # than raised out of the first `relative_to` that meets it.
        print(
            f"{arguments.root}/ is outside {arguments.repo}/; the records live in the repository they "
            "bind",
            file=sys.stderr,
        )
        return 1

    records = collect_records(decisions, repo)
    index_path = decisions / "README.md"
    index = render_index(records)

    if arguments.write:
        index_path.write_text(index, encoding="utf-8")
        print(
            f"wrote {index_path.relative_to(repo).as_posix()} "
            f"({len(records)} record{plural(len(records))})"
        )
        return 0

    check(records, collect_rules(repo, decisions), repo, decisions)
    index_where = index_path.relative_to(repo).as_posix()
    if not index_path.is_file():
        fail(index_where, f"missing; run `{rerun_command(repo)}`")
    elif read(index_path) != index:
        fail(index_where, f"is out of date; run `{rerun_command(repo)}`")

    if problems:
        sys.stderr.write("\n".join("  " + line for line in problems) + "\n")
        sys.stderr.write(f"\n{len(problems)} problem(s).\n")
        return 1
    print(f"{len(records)} record{plural(len(records))}, index current, no problems")
    return 0


if __name__ == "__main__":
    sys.exit(main())
